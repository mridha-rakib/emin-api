import { Body, Controller, Delete, Get, Param, Patch, Post, Query } from '@nestjs/common';
import { PaginationQueryDto } from '../../../common/dto/pagination-query.dto';
import { ParseObjectIdPipe } from '../../../common/pipes/parse-object-id.pipe';
import { CreateAutoBidDto } from '../dto/create-auto-bid.dto';
import { UpdateAutoBidDto } from '../dto/update-auto-bid.dto';
import { AutoBidService } from '../services/auto-bid.service';

@Controller('auto-bids')
export class AutoBidController {
  constructor(private readonly service: AutoBidService) {}

  @Post()
  create(@Body() dto: CreateAutoBidDto) {
    return this.service.create(dto);
  }

  @Get()
  findAll(@Query() query: PaginationQueryDto) {
    return this.service.findAll(query);
  }

  @Get(':id')
  findOne(@Param('id', ParseObjectIdPipe) id: string) {
    return this.service.findOne(id);
  }

  @Patch(':id')
  update(@Param('id', ParseObjectIdPipe) id: string, @Body() dto: UpdateAutoBidDto) {
    return this.service.update(id, dto);
  }

  @Delete(':id')
  remove(@Param('id', ParseObjectIdPipe) id: string) {
    return this.service.remove(id);
  }
}